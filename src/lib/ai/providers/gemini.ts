import { supabase } from '../../supabase';
import { AIProvider, ToolDefinition, validateInputLimits } from './provider';
import { AIInput, AIOutput, AIError, AI_MODELS } from '../types';

/**
 * GeminiProvider
 * Implementación híbrida desacoplada:
 * 1. Invoca de forma segura la Edge Function 'ai' de Supabase (ideal para producción).
 * 2. Si no está desplegada (404) y se configuró EXPO_PUBLIC_GEMINI_API_KEY, conecta directamente a Gemini REST (ideal para desarrollo local y dev-client).
 */
export class GeminiProvider implements AIProvider {
  private readonly functionName = 'ai';

  private async invokeBackend<T>(payload: Record<string, unknown>): Promise<T> {
    const directApiKey = process.env.EXPO_PUBLIC_GEMINI_API_KEY || '';

    // Si hay API Key configurada directamente en el cliente, usarla para máxima velocidad y evitar errores de Edge Function no desplegada
    if (directApiKey) {
      try {
        return await this.invokeGeminiDirect<T>(payload, directApiKey);
      } catch (directErr: any) {
        console.warn('[GeminiProvider] Direct API call error, intentando Edge Function...', directErr);
      }
    }

    try {
      const { data, error } = await supabase.functions.invoke(this.functionName, {
        body: payload,
      });

      if (error) {
        throw await this.handleBackendError(error);
      }

      if (!data) {
        throw {
          code: 'provider_error',
          message: 'Empty response received from AI backend',
          userMessage: 'No se recibió respuesta del servicio de inteligencia artificial.',
          retryable: true,
        } as AIError;
      }

      return data as T;
    } catch (err: any) {
      console.error('[GeminiProvider] invokeBackend error:', err);
      if (err.code && err.userMessage) {
        throw err;
      }
      throw this.handleNetworkOrUnknownError(err);
    }
  }

  /**
   * Llamada directa a Google Generative AI REST API cuando se cuenta con EXPO_PUBLIC_GEMINI_API_KEY
   */
  private async invokeGeminiDirect<T>(payload: Record<string, unknown>, apiKey: string): Promise<T> {
    const input = payload.input as AIInput;
    const systemPrompt = payload.systemPrompt as string | undefined;
    const model = (payload.model as string) || 'gemini-2.0-flash';

    const parts: any[] = [];
    if (input.text) {
      parts.push({ text: input.text });
    } else {
      const hasImagesOrDocs = Array.isArray(input.attachments) && input.attachments.some((a: any) =>
        a.mimeType?.startsWith('image/') || a.type === 'image' || a.mimeType?.includes('pdf') || a.type === 'pdf'
      );
      if (hasImagesOrDocs) {
        parts.push({ text: 'Analiza con máxima atención la imagen o documento adjunto (puede ser un horario de clases, turnos, factura, recibo, lista de tareas o cita) y extrae todos los datos estructurados en formato JSON según las instrucciones del sistema.' });
      } else {
        parts.push({ text: 'Escucha el audio adjunto con atención y devuelve el JSON requerido con la intención y la transcripción textual.' });
      }
    }

    if (Array.isArray(input.attachments)) {
      for (const att of input.attachments) {
        if (att.base64Data) {
          const cleanData = att.base64Data.replace(/^data:[^;]+;base64,/, '');
          parts.push({
            inlineData: {
              mimeType: att.mimeType,
              data: cleanData,
            },
          });
        }
      }
    }

    const requestBody: any = {
      contents: [{ parts }],
      generationConfig: {
        responseMimeType: 'application/json',
        temperature: 0.2,
      },
    };

    if (systemPrompt) {
      requestBody.systemInstruction = {
        parts: [{ text: systemPrompt }],
      };
    }

    const url = `https://generativelanguage.googleapis.com/v1beta/models/${model}:generateContent?key=${apiKey}`;

    const res = await fetch(url, {
      method: 'POST',
      headers: {
        'Content-Type': 'application/json',
      },
      body: JSON.stringify(requestBody),
    });

    if (!res.ok) {
      const errText = await res.text();
      console.error('[GeminiProvider] Direct call failed:', res.status, errText);
      throw {
        code: this.mapErrorCode(errText, res.status),
        message: `Gemini API returned ${res.status}: ${errText}`,
        userMessage: this.getFriendlyErrorMessage(errText, res.status),
        retryable: res.status === 429 || res.status === 503,
      } as AIError;
    }

    const json = await res.json();
    const candidateText = json.candidates?.[0]?.content?.parts?.[0]?.text;

    if (!candidateText) {
      throw {
        code: 'provider_error',
        message: 'No text generated by Gemini',
        userMessage: 'La IA no generó contenido para esta solicitud.',
        retryable: true,
      } as AIError;
    }

    let structured: any = {};
    try {
      structured = JSON.parse(candidateText);
    } catch {
      structured = { rawText: candidateText };
    }

    if (payload.action === 'generateStructured') {
      return { structured } as unknown as T;
    }

    return {
      structured,
      text: candidateText,
    } as unknown as T;
  }

  async generateText(input: AIInput, systemPrompt?: string): Promise<AIOutput> {
    const limitError = validateInputLimits(input);
    if (limitError) throw limitError;

    return this.invokeBackend<AIOutput>({
      action: 'generateText',
      model: AI_MODELS.TEXT,
      input,
      systemPrompt,
    });
  }

  async generateStructured<T>(input: AIInput, schemaName: string, systemPrompt?: string): Promise<T> {
    const limitError = validateInputLimits(input);
    if (limitError) throw limitError;

    const res = await this.invokeBackend<{ structured: T }>({
      action: 'generateStructured',
      model: AI_MODELS.TEXT,
      input,
      schemaName,
      systemPrompt,
    });

    return res.structured;
  }

  async generateMultimodal(input: AIInput, systemPrompt?: string): Promise<AIOutput> {
    const limitError = validateInputLimits(input);
    if (limitError) throw limitError;

    return this.invokeBackend<AIOutput>({
      action: 'generateMultimodal',
      model: AI_MODELS.MULTIMODAL,
      input,
      systemPrompt,
    });
  }

  async executeTools(input: AIInput, tools: ToolDefinition[], systemPrompt?: string): Promise<AIOutput> {
    const limitError = validateInputLimits(input);
    if (limitError) throw limitError;

    return this.invokeBackend<AIOutput>({
      action: 'executeTools',
      model: AI_MODELS.TEXT,
      input,
      tools,
      systemPrompt,
    });
  }

  async isAvailable(): Promise<boolean> {
    if (process.env.EXPO_PUBLIC_GEMINI_API_KEY) {
      return true;
    }
    try {
      const { data } = await supabase.auth.getSession();
      return !!data.session;
    } catch {
      return false;
    }
  }

  private async handleBackendError(error: any): Promise<AIError> {
    let serverDetail = '';
    try {
      if (error?.context && typeof error.context.json === 'function') {
        const body = await error.context.json();
        if (body?.error) serverDetail = String(body.error);
        if (body?.message) serverDetail = serverDetail ? `${serverDetail} - ${body.message}` : String(body.message);
      }
    } catch {
      // Ignorar si no se pudo parsear json
    }

    const status = error.status || error.statusCode || error.context?.status;
    console.error('[GeminiProvider] Edge Function Error:', { status, message: error.message, detail: serverDetail });

    const fullErrorStr = `${serverDetail} ${error?.message || ''}`;
    const userMessage = this.getFriendlyErrorMessage(fullErrorStr, status);

    return {
      code: this.mapErrorCode(fullErrorStr, status),
      message: serverDetail || error.message || 'Backend AI invocation failed',
      userMessage,
      retryable: status === 429 || status === 503 || fullErrorStr.includes('429') || fullErrorStr.includes('503'),
    };
  }

  private handleNetworkOrUnknownError(err: any): AIError {
    const msg = String(err?.message || err);
    console.error('[GeminiProvider] Network/Unknown error:', msg);

    if (msg.includes('Network request failed') || msg.includes('Failed to fetch')) {
      return {
        code: 'offline',
        message: msg,
        userMessage: 'Sin conexión a internet. La IA requiere conexión activa.',
        retryable: true,
      };
    }

    return {
      code: 'network_error',
      message: msg,
      userMessage: this.getFriendlyErrorMessage(msg),
      retryable: true,
    };
  }

  private getFriendlyErrorMessage(errorText: string, status?: number): string {
    const text = (errorText || '').toLowerCase();

    // 1. Cuota excedida / Rate limit (429, Quota exceeded, Too Many Requests)
    if (
      status === 429 ||
      text.includes('429') ||
      text.includes('too many requests') ||
      text.includes('quota') ||
      text.includes('rate limit') ||
      text.includes('resource_exhausted')
    ) {
      const retryMatch = errorText.match(/retry in ([0-9]+(?:\.[0-9]+)?)s/i) || errorText.match(/retryDelay["']?:\s*["']?([0-9]+)s/i);
      const seconds = retryMatch ? Math.ceil(parseFloat(retryMatch[1])) : null;
      if (seconds && seconds > 0 && seconds <= 120) {
        return `Límite de consultas alcanzado. Por favor, espera ${seconds} segundos para volver a intentarlo.`;
      }
      return 'Has alcanzado el límite temporal de consultas de la IA. Por favor, espera unos instantes e inténtalo de nuevo.';
    }

    // 2. Servidores con alta demanda o saturados (503, Overloaded, Unavailable)
    if (
      status === 503 ||
      text.includes('503') ||
      text.includes('high demand') ||
      text.includes('overloaded') ||
      text.includes('service unavailable')
    ) {
      return 'Los servidores de la IA tienen alta demanda en este momento. Intenta de nuevo en unos segundos.';
    }

    // 3. Claves de API / Permisos / Autenticación
    if (
      status === 401 ||
      status === 403 ||
      text.includes('gemini_api_key') ||
      text.includes('api_key_invalid') ||
      text.includes('unauthorized') ||
      text.includes('permission_denied')
    ) {
      return 'La configuración del servicio de IA requiere revisión. Verifica la clave API en Supabase.';
    }

    // 4. Servicio o modelo no disponible temporalmente (404)
    if (
      status === 404 ||
      text.includes('requested function was not found') ||
      text.includes('function was not found') ||
      text.includes('function not found')
    ) {
      return 'La Edge Function de IA no está desplegada en Supabase y no se ha configurado EXPO_PUBLIC_GEMINI_API_KEY en el archivo .env. Agrega tu clave en .env (EXPO_PUBLIC_GEMINI_API_KEY=tu_api_key) para usar la IA directamente.';
    }

    if (
      text.includes('404') ||
      text.includes('not found') ||
      text.includes('not supported') ||
      text.includes('no longer available')
    ) {
      return 'El servicio de IA no se encuentra disponible temporalmente. Por favor, intenta más tarde.';
    }

    // 5. Conexión y red
    if (
      text.includes('network') ||
      text.includes('timeout') ||
      text.includes('econnreset') ||
      text.includes('failed to fetch')
    ) {
      return 'Problema de conexión con el servicio de IA. Revisa tu internet e inténtalo de nuevo.';
    }

    // 6. Mensaje por defecto amigable (NUNCA mostrar URLs, JSON o stack traces internos al usuario)
    return 'No se pudo completar la solicitud con la IA en este momento. Intenta de nuevo.';
  }

  private mapErrorCode(errorText: string, status?: number): AIError['code'] {
    const text = (errorText || '').toLowerCase();
    if (status === 429 || text.includes('429') || text.includes('quota') || text.includes('rate limit')) {
      return 'rate_limit';
    }
    if (status === 401 || status === 403 || text.includes('unauthorized') || text.includes('permission')) {
      return 'auth_error';
    }
    if (text.includes('network') || text.includes('failed to fetch')) {
      return 'network_error';
    }
    return 'provider_error';
  }
}
